const fs = require('fs');

// This line makes it possible to use a .env file for local development.
// On a hosting provider, you'll set these variables in the dashboard.
require('dotenv').config();

console.log('Generating firebase-config.js...');

// Get the environment variables. The `process.env` object is where Node.js
// stores environment variables.
const firebaseConfig = {
  apiKey: process.env.FIREBASE_API_KEY,
  authDomain: process.env.FIREBASE_AUTH_DOMAIN,
  databaseURL: process.env.FIREBASE_DATABASE_URL,
  projectId: process.env.FIREBASE_PROJECT_ID,
  storageBucket: process.env.FIREBASE_STORAGE_BUCKET,
  messagingSenderId: process.env.FIREBASE_MESSAGING_SENDER_ID,
  appId: process.env.FIREBASE_APP_ID,
  measurementId: process.env.FIREBASE_MEASUREMENT_ID
};

// --- VALIDATION ---
// Check if all required Firebase config values are present.
const requiredKeys = ['apiKey', 'authDomain', 'databaseURL', 'projectId', 'storageBucket', 'messagingSenderId', 'appId'];
const missingKeys = requiredKeys.filter(key => !firebaseConfig[key]);

if (missingKeys.length > 0) {
  console.error('🔴 FATAL ERROR: Missing required Firebase environment variables:');
  console.error(missingKeys.join(', '));
  console.error('Please ensure your .env file is correct and all variables are set.');
  // Exit the script with an error code to prevent a broken build.
  process.exit(1); 
}
// --- END VALIDATION ---


// Create the content of the firebase-config.js file.
const configFileContent = `
// This file is auto-generated by the build script.
// Do not edit it manually, as your changes will be overwritten.

const firebaseConfig = ${JSON.stringify(firebaseConfig, null, 2)};

// Initialize Firebase
firebase.initializeApp(firebaseConfig);
`;

// Write the content to the file.
fs.writeFileSync('firebase-config.js', configFileContent);

console.log('firebase-config.js generated successfully!');